const char *E(GLenum e)
{
    for (const EnumName &n : k_enums)
        if (n.value == e) return n.name;
    if (e >= GL_TEXTURE0 && e <= GL_TEXTURE31) {
        static const char *const units[] = {
            "GL_TEXTURE0",  "GL_TEXTURE1",  "GL_TEXTURE2",  "GL_TEXTURE3",  "GL_TEXTURE4",  "GL_TEXTURE5",
            "GL_TEXTURE6",  "GL_TEXTURE7",  "GL_TEXTURE8",  "GL_TEXTURE9",  "GL_TEXTURE10", "GL_TEXTURE11",
            "GL_TEXTURE12", "GL_TEXTURE13", "GL_TEXTURE14", "GL_TEXTURE15", "GL_TEXTURE16", "GL_TEXTURE17",
            "GL_TEXTURE18", "GL_TEXTURE19", "GL_TEXTURE20", "GL_TEXTURE21", "GL_TEXTURE22", "GL_TEXTURE23",
            "GL_TEXTURE24", "GL_TEXTURE25", "GL_TEXTURE26", "GL_TEXTURE27", "GL_TEXTURE28", "GL_TEXTURE29",
            "GL_TEXTURE30", "GL_TEXTURE31"};
        return units[e - GL_TEXTURE0];
    }
    return hex(e);
}

const char *E_blend(GLenum e)
{
    if (e == GL_ZERO) return "GL_ZERO";
    if (e == GL_ONE) return "GL_ONE";
    return E(e);
}

const char *E_prim(GLenum e)
{
    static const char *const prims[] = {"GL_POINTS",    "GL_LINES",          "GL_LINE_LOOP", "GL_LINE_STRIP",
                                        "GL_TRIANGLES", "GL_TRIANGLE_STRIP", "GL_TRIANGLE_FAN", "GL_QUADS",
                                        "GL_QUAD_STRIP", "GL_POLYGON"};
    return e < 10 ? prims[e] : hex(e);
}

const char *E_ifmt(GLint e)
{
    static const char *const legacy[] = {"0", "1", "2", "3", "4"};
    return (e >= 0 && e <= 4) ? legacy[e] : E((GLenum)e);
}

const char *E_clear(GLbitfield m)
{
    static thread_local char buf[96];
    snprintf(buf, sizeof buf, "%s%s%s%s", (m & GL_COLOR_BUFFER_BIT) ? "COLOR " : "",
             (m & GL_DEPTH_BUFFER_BIT) ? "DEPTH " : "", (m & GL_STENCIL_BUFFER_BIT) ? "STENCIL " : "",
             (m & ~(GLbitfield)(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT | GL_STENCIL_BUFFER_BIT)) ? "OTHER " : "");
    size_t n = strlen(buf);
    if (n) buf[n - 1] = 0;
    return buf;
}

uint64_t wb_hash(const void *data, size_t len)
{
    const unsigned char *p = (const unsigned char *)data;
    uint64_t h = 0xcbf29ce484222325ull; // FNV-1a
    for (size_t i = 0; i < len; i++) h = (h ^ p[i]) * 0x100000001b3ull;
    return h;
}
